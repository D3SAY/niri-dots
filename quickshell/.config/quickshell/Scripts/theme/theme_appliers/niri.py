import os

from color_utils import sanitize_color


def apply(home, colors):
    accent = sanitize_color(colors["accent"])
    border = sanitize_color(colors["border"])
    muted = sanitize_color(colors["muted"])
    shadow = sanitize_color(colors["shadow"])
    accentComplementary = sanitize_color(colors["accentComplementary"])

    # config.kdl includes this file; niri reloads it on change
    content = f"""// Generated by Quickshell Theme service
layout {{
    tab-indicator {{
        active-color "{accent}"
        inactive-color "{muted}"
        urgent-color "{accentComplementary}"
    }}
    insert-hint {{
        color "{accent}40"
    }}
    shadow {{
        color "{shadow}70"
    }}
    border {{
        active-color "{accent}"
        inactive-color "{border}"
    }}
}}
"""
    niri_dir = os.path.join(home, ".config", "niri")
    os.makedirs(niri_dir, exist_ok=True)
    with open(os.path.join(niri_dir, "colors.kdl"), "w") as f:
        f.write(content)
