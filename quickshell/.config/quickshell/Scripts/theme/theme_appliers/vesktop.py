import os

from color_utils import blend_hex, sanitize_color


def apply(home, colors):
    """Vesktop (Discord): a theme file in its themes folder; it reloads the file on change."""
    themes = os.path.join(home, ".config", "vesktop", "themes")
    if not os.path.isdir(os.path.dirname(themes)):
        return

    bg = sanitize_color(colors.get("opaqueBg", colors["bg"]))
    fg = sanitize_color(colors["fg"])
    accent = sanitize_color(colors["accent"])
    alt = sanitize_color(colors["accentComplementary"])

    # surfaces step up from the wallpaper background toward the text color, like the shell's cards
    base_lowest = blend_hex(bg, "#000000", 0.7)
    base_lower = bg
    base_low = blend_hex(fg, bg, 0.035)
    surface = blend_hex(fg, bg, 0.06)
    surface_high = blend_hex(fg, bg, 0.09)
    surface_higher = blend_hex(fg, bg, 0.12)
    hover = blend_hex(fg, bg, 0.07)
    selected = blend_hex(accent, bg, 0.18)
    border = blend_hex(fg, bg, 0.10)
    muted = blend_hex(fg, bg, 0.55)
    faint = blend_hex(fg, bg, 0.35)
    accent_hover = blend_hex(accent, fg, 0.15)
    accent_text = bg

    css = f"""/**
 * @name minflair
 * @description Colors from the wallpaper, generated by Quickshell (theme_appliers/vesktop.py)
 * @author niri-dots
 */

:root, .theme-dark, .theme-darker, .theme-midnight, .visual-refresh {{
    --font-primary: "Geist", "gg sans", sans-serif;
    --font-display: "Geist", "gg sans", sans-serif;
    --font-code: "CaskaydiaCove Nerd Font Mono", monospace;

    /* backgrounds, new and old names */
    --background-base-lowest: {base_lowest};
    --background-base-lower: {base_lower};
    --background-base-low: {base_low};
    --background-surface-high: {surface};
    --background-surface-higher: {surface_high};
    --background-surface-highest: {surface_higher};
    --chat-background-default: {base_lower};
    --bg-base-primary: {base_lower};
    --bg-base-secondary: {base_low};
    --bg-base-tertiary: {base_lowest};
    --bg-surface-raised: {surface};
    --bg-surface-overlay: {surface_high};
    --background-primary: {base_lower};
    --background-secondary: {base_low};
    --background-secondary-alt: {surface};
    --background-tertiary: {base_lowest};
    --background-floating: {surface_high};
    --background-nested-floating: {surface_higher};
    --background-accent: {selected};
    --modal-background: {base_low};
    --modal-footer-background: {base_lowest};
    --home-background: {base_lower};
    --channeltextarea-background: {surface};
    --input-background: {surface};
    --input-background-default: {surface};
    --card-primary-bg: {surface};
    --deprecated-card-bg: {surface};
    --background-modifier-hover: {hover};
    --background-modifier-selected: {selected};
    --background-modifier-active: {selected};
    --background-mod-subtle: {hover};
    --background-mod-normal: {surface_high};
    --background-mod-strong: {surface_higher};
    --interactive-background-hover: {hover};
    --interactive-background-selected: {selected};
    --scrollbar-thin-thumb: {surface_higher};
    --scrollbar-auto-thumb: {surface_higher};
    --scrollbar-auto-track: transparent;

    /* lines */
    --border-subtle: {border};
    --border-normal: {border};
    --border-strong: {surface_higher};
    --background-modifier-accent: {border};

    /* text */
    --text-default: {fg};
    --text-normal: {fg};
    --text-strong: {fg};
    --header-primary: {fg};
    --header-secondary: {muted};
    --text-muted: {muted};
    --text-subtle: {muted};
    --channels-default: {muted};
    --channel-icon: {muted};
    --interactive-normal: {muted};
    --interactive-hover: {fg};
    --interactive-active: {fg};
    --interactive-muted: {faint};
    --interactive-text-default: {muted};
    --interactive-text-hover: {fg};
    --interactive-text-active: {fg};
    --icon-default: {muted};
    --icon-strong: {fg};
    --text-link: {accent};
    --text-brand: {accent};

    /* accent: buttons, mentions, unread dots, sliders */
    --brand-experiment: {accent};
    --brand-500: {accent};
    --brand-560: {accent_hover};
    --brand-600: {accent_hover};
    --brand-360: {accent};
    --control-brand-foreground: {accent};
    --control-brand-foreground-new: {accent};
    --button-filled-brand-background: {accent};
    --button-filled-brand-background-hover: {accent_hover};
    --button-filled-brand-text: {accent_text};
    --bg-brand: {accent};
    --mention-foreground: {accent};
    --mention-background: color-mix(in srgb, {accent} 18%, transparent);
    --info-help-foreground: {alt};

    /* smaller corners, like the rest of the desktop */
    --radius-xs: 4px;
    --radius-sm: 6px;
    --radius-md: 8px;
    --radius-lg: 10px;
}}

/* the light-on-accent text inside brand buttons */
[class*="colorBrand"], [class*="lookFilled"][class*="colorBrand"] {{
    color: {accent_text} !important;
}}

::selection {{
    background: color-mix(in srgb, {accent} 35%, transparent);
}}
"""
    os.makedirs(themes, exist_ok=True)
    with open(os.path.join(themes, "minflair.css"), "w") as f:
        f.write(css)
