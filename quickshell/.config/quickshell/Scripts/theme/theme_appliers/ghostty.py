import os
import subprocess

from color_utils import sanitize_color


def apply(home, colors):
    bg = sanitize_color(colors.get("opaqueBg", colors["bg"]))
    fg = sanitize_color(colors["fg"])
    accent = sanitize_color(colors["accent"])
    bgSecondary = sanitize_color(colors["bgSecondary"])

    # Only the base colors follow the wallpaper; the 16 ANSI colors stay default for readability
    content = f"""# Generated by Quickshell Theme service
background = {bg}
foreground = {fg}
cursor-color = {accent}
cursor-text = {bg}
selection-background = {bgSecondary}
selection-foreground = {fg}
"""
    theme_dir = os.path.join(home, ".config", "ghostty", "themes")
    os.makedirs(theme_dir, exist_ok=True)
    with open(os.path.join(theme_dir, "minflair"), "w") as f:
        f.write(content)
    # ghostty reloads its config on SIGUSR2
    subprocess.run(
        ["pkill", "-USR2", "-x", "ghostty"],
        stderr=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
    )
