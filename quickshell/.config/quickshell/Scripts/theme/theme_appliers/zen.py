import glob
import os

from color_utils import sanitize_color

IMPORT = '@import "minflair.css";'
PREF = 'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);'


def apply(home, colors):
    bg = sanitize_color(colors.get("opaqueBg", colors["bg"]))
    fg = sanitize_color(colors["fg"])
    accent = sanitize_color(colors["accent"])
    surface = sanitize_color(colors["bgSecondary"])
    surface_high = sanitize_color(colors["bgTertiary"])
    border = sanitize_color(colors["border"])

    css = f"""/* Generated by Quickshell Theme service */
:root {{
    --zen-primary-color: {accent} !important;
    --zen-colors-primary: {surface} !important;
    --zen-colors-secondary: {surface_high} !important;
    --zen-colors-tertiary: {bg} !important;
    --zen-colors-border: {border} !important;
    --zen-main-browser-background: {bg} !important;
    --zen-main-browser-background-toolbar: {bg} !important;
    --zen-themed-toolbar-bg-transparent: {bg} !important;
    --zen-dialog-background: {surface} !important;
    --zen-urlbar-background-base: {surface} !important;
    --toolbar-bgcolor: {bg} !important;
    --toolbar-color: {fg} !important;
    --toolbox-textcolor: {fg} !important;
    --sidebar-text-color: {fg} !important;
    --tab-selected-textcolor: {fg} !important;
    --toolbar-field-background-color: {surface} !important;
    --toolbar-field-focus-background-color: {surface} !important;
    --toolbar-field-color: {fg} !important;
    --toolbar-field-focus-color: {fg} !important;
    --arrowpanel-background: {surface} !important;
    --arrowpanel-color: {fg} !important;
    --focus-outline-color: {accent} !important;
}}
"""
    # Zen profiles have random folder names; colors apply on the next Zen start
    for profile in glob.glob(os.path.join(home, ".config", "zen", "*", "")):
        if not os.path.exists(os.path.join(profile, "prefs.js")):
            continue
        chrome = os.path.join(profile, "chrome")
        os.makedirs(chrome, exist_ok=True)
        with open(os.path.join(chrome, "minflair.css"), "w") as f:
            f.write(css)

        user_chrome = os.path.join(chrome, "userChrome.css")
        lines = []
        if os.path.exists(user_chrome):
            with open(user_chrome) as f:
                lines = f.read().splitlines()
        # @import must come first; drop the old matugen import
        lines = [l for l in lines if l.strip() not in (IMPORT, '@import "matugen.css";')]
        with open(user_chrome, "w") as f:
            f.write("\n".join([IMPORT] + lines) + "\n")

        user_js = os.path.join(profile, "user.js")
        existing = open(user_js).read() if os.path.exists(user_js) else ""
        if PREF not in existing:
            with open(user_js, "a") as f:
                f.write(PREF + "\n")
