import os

from color_utils import blend_hex, sanitize_color


def apply(home, colors):
    """mpv's uosc interface: wallpaper colors for the timeline, controls and menus."""
    bg = sanitize_color(colors.get("opaqueBg", colors["bg"]))
    fg = sanitize_color(colors["fg"])
    accent = sanitize_color(colors["accent"])
    curtain = blend_hex(bg, "#000000", 0.6)

    def hx(c):
        return c.lstrip("#")

    # uosc reads only this file for its options; settings that aren't colors live here too
    content = f"""# Generated by Quickshell Theme service (colors follow the wallpaper)
timeline_style=line
timeline_line_width=2
timeline_size=36
progress=windowed
progress_size=2
controls_size=28
top_bar=no-border
border_radius=6
font_bold=no
pause_indicator=flash
autoload=yes
color=foreground={hx(accent)},foreground_text={hx(bg)},background={hx(bg)},background_text={hx(fg)},curtain={hx(curtain)}
opacity=timeline=0.85,menu=0.95,curtain=0.6
"""
    path = os.path.join(home, ".config", "mpv", "script-opts", "uosc.conf")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)
