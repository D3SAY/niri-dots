#!/usr/bin/env python3
import sys

sys.dont_write_bytecode = True

import re
import subprocess
from pathlib import Path


def main():
    if len(sys.argv) < 3:
        print("Usage: apply_cursor.py <ThemeName> <Size>")
        sys.exit(1)

    theme_name = sys.argv[1]
    size = sys.argv[2]
    home = Path.home()

    # 1. Update GTK globally via gsettings
    subprocess.run(
        ["gsettings", "set", "org.gnome.desktop.interface", "cursor-theme", theme_name],
        capture_output=True,
    )
    subprocess.run(
        ["gsettings", "set", "org.gnome.desktop.interface", "cursor-size", size],
        capture_output=True,
    )

    # 2. Update ~/.icons/default/index.theme
    icons_dir = home / ".icons" / "default"
    icons_dir.mkdir(parents=True, exist_ok=True)
    index_theme_path = icons_dir / "index.theme"

    content = f"[Icon Theme]\nInherits={theme_name}\n"
    index_theme_path.write_text(content, encoding="utf-8")

    # 3. niri: cursor theme for the compositor itself, in an include read by config.kdl
    cursor_kdl = home / ".config" / "niri" / "cursor.kdl"
    try:
        cursor_kdl.parent.mkdir(parents=True, exist_ok=True)
        cursor_kdl.write_text(
            "// Generated by Quickshell (Settings app)\n"
            f'cursor {{\n    xcursor-theme "{theme_name}"\n    xcursor-size {size}\n}}\n',
            encoding="utf-8",
        )
    except Exception as e:
        print(f"Warning: Failed to update niri cursor: {e}", file=sys.stderr)


if __name__ == "__main__":
    main()
