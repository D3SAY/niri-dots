import os

from color_utils import blend_hex, sanitize_color


def apply(home, colors):
    """swayimg: wallpaper colors in a Lua file that ~/.config/swayimg/init.lua loads."""
    bg = sanitize_color(colors.get("opaqueBg", colors["bg"]))
    fg = sanitize_color(colors["fg"])
    accent = sanitize_color(colors["accent"])
    tile = blend_hex(fg, bg, 0.06)
    tile_selected = blend_hex(accent, bg, 0.25)
    checker_a = blend_hex(fg, bg, 0.08)
    checker_b = blend_hex(fg, bg, 0.14)

    def argb(c, alpha="ff"):
        return "0x" + alpha + c.lstrip("#")

    content = f"""-- Generated by Quickshell Theme service (colors follow the wallpaper)
return {{
  background = {argb(bg)},
  text = {argb(fg)},
  text_background = {argb(bg, "b3")},
  accent = {argb(accent)},
  tile = {argb(tile)},
  tile_selected = {argb(tile_selected)},
  checker_a = {argb(checker_a)},
  checker_b = {argb(checker_b)},
}}
"""
    path = os.path.join(home, ".config", "swayimg", "colors.lua")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)
