import os
import shutil
import subprocess

from color_utils import blend_hex, sanitize_color

USER_CSS = """/* minflair for Spotify: colors come from color.ini, this only tones the shapes down */
:root {
    --font-family: "Geist", "Spotify Mix", sans-serif !important;
}

body, .encore-dark-theme, .encore-base-set {
    font-family: var(--font-family) !important;
}

/* smaller corners, like the rest of the desktop */
.main-yourLibraryX-entryPoints, .Root__nav-bar, .Root__main-view, .Root__right-sidebar,
.main-card-card, .main-trackList-trackListRow, .x-entityImage-imageContainer,
.main-image-image, .main-coverSlotCollapsed-container {
    border-radius: 8px !important;
}

/* flat cards instead of Spotify's gradients */
.main-entityHeader-backgroundColor, .main-actionBarBackground-background,
.main-home-homeHeader, .before-scroll-node > div {
    background: var(--spice-main) !important;
    background-image: none !important;
}

.main-card-card {
    background: var(--spice-card) !important;
}

.main-card-card:hover {
    background: var(--spice-selected-row) !important;
}

/* thin progress and volume bars in the accent color */
.progress-bar {
    --progress-bar-height: 3px !important;
    --fg-color: var(--spice-button) !important;
}
"""


def apply(home, colors):
    """Spotify through Spicetify: a 'minflair' theme whose color.ini follows the wallpaper."""
    config = os.path.join(home, ".config", "spicetify")
    if not os.path.isdir(config):
        return

    bg = sanitize_color(colors.get("opaqueBg", colors["bg"]))
    fg = sanitize_color(colors["fg"])
    accent = sanitize_color(colors["accent"])
    alt = sanitize_color(colors["accentComplementary"])

    def hx(c):
        return c.lstrip("#")

    scheme = {
        "text": fg,
        "subtext": blend_hex(fg, bg, 0.6),
        "main": bg,
        "main-elevated": blend_hex(fg, bg, 0.06),
        "highlight": blend_hex(fg, bg, 0.08),
        "highlight-elevated": blend_hex(fg, bg, 0.12),
        "sidebar": blend_hex(bg, "#000000", 0.7),
        "player": blend_hex(bg, "#000000", 0.7),
        "card": blend_hex(fg, bg, 0.04),
        "shadow": "#000000",
        "selected-row": blend_hex(fg, bg, 0.10),
        "button": accent,
        "button-active": blend_hex(accent, fg, 0.15),
        "button-disabled": blend_hex(fg, bg, 0.3),
        "tab-active": blend_hex(fg, bg, 0.12),
        "notification": blend_hex(accent, bg, 0.35),
        "notification-error": alt,
        "misc": blend_hex(fg, bg, 0.2),
    }
    ini = "; Generated by Quickshell Theme service (colors follow the wallpaper)\n[base]\n"
    ini += "".join(f"{k:<20}= {hx(v)}\n" for k, v in scheme.items())

    theme = os.path.join(config, "Themes", "minflair")
    os.makedirs(theme, exist_ok=True)
    with open(os.path.join(theme, "color.ini"), "w") as f:
        f.write(ini)
    with open(os.path.join(theme, "user.css"), "w") as f:
        f.write(USER_CSS)

    # push the new colors into Spotify's files; Spotify shows them on its next start
    if shutil.which("spicetify"):
        subprocess.Popen(
            ["spicetify", "refresh", "-q"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
