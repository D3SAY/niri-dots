#!/usr/bin/env python3
"""Read, update and render compositor settings for niri.

  niri_prefs.py read            print the saved settings as JSON
  niri_prefs.py write '<json>'  merge keys into the saved settings and regenerate the niri include

Settings live in ~/.cache/quickshell/niri_prefs.json; ~/.config/niri/minflair.kdl is generated
from them and included by config.kdl (niri reloads it on change). Keys starting with "_" are
temporary overrides (power saver, game mode) that win over the user's choices.
"""
import json
import os
import sys

sys.dont_write_bytecode = True

HOME = os.path.expanduser("~")
PREFS = os.path.join(HOME, ".cache", "quickshell", "niri_prefs.json")
KDL = os.path.join(HOME, ".config", "niri", "minflair.kdl")

DEFAULTS = {
    "animations": True,
    "animationSpeed": 1.0,
    "rounding": 8,
    "activeOpacity": 100,
    "inactiveOpacity": 100,
    "gaps": 10,
    "borderSize": 0,
    "shadow": True,
    "shadowRange": 8,
    "mouseSensitivity": 0.0,
    "mouseAccelProfile": "flat",
    "mouseNaturalScroll": False,
    "mouseScrollFactor": 1.0,
    "mouseLeftHanded": False,
    "focusFollowsMouse": True,
    "cursorInactiveTimeout": 5,
    "touchpadNaturalScroll": True,
    "touchpadTapToClick": True,
    "touchpadDisableWhileTyping": True,
    "_powerSaver": False,
    "_gameMode": False,
}


def load():
    prefs = dict(DEFAULTS)
    try:
        with open(PREFS) as f:
            prefs.update(json.load(f))
    except (OSError, ValueError):
        pass
    return prefs


def flag(name, on, indent):
    return f"{indent}{name}\n" if on else ""


def render(p):
    reduced = p["_powerSaver"] or p["_gameMode"]
    animations = p["animations"] and not reduced
    shadow = p["shadow"] and not reduced
    speed = max(0.1, float(p["animationSpeed"]))

    out = ["// Generated by Quickshell (Settings app); edit settings there, not here\n"]

    if animations:
        # niri's slowdown is the inverse of a speed factor
        out.append(f"animations {{\n    slowdown {1.0 / speed:.2f}\n}}\n")
    else:
        out.append("animations {\n    off\n}\n")

    border = int(p["borderSize"])
    out.append("layout {\n")
    out.append(f"    gaps {int(p['gaps'])}\n")
    if border > 0:
        out.append(f"    border {{\n        width {border}\n    }}\n")
    else:
        out.append("    border {\n        off\n    }\n")
    if shadow:
        out.append(
            f"    shadow {{\n        on\n        softness {int(p['shadowRange']) * 3}\n"
            f"        spread {max(1, int(p['shadowRange']) // 2)}\n        offset x=0 y=4\n    }}\n"
        )
    else:
        out.append("    shadow {\n        off\n    }\n")
    out.append("}\n")

    out.append(
        f"window-rule {{\n    geometry-corner-radius {int(p['rounding'])}\n    clip-to-geometry true\n"
        f"    opacity {int(p['activeOpacity']) / 100:.2f}\n}}\n"
    )
    if int(p["inactiveOpacity"]) != int(p["activeOpacity"]):
        out.append(
            f"window-rule {{\n    match is-active=false\n    opacity {int(p['inactiveOpacity']) / 100:.2f}\n}}\n"
        )

    sens = max(-1.0, min(1.0, float(p["mouseSensitivity"])))
    out.append("input {\n    mouse {\n")
    out.append(f"        accel-speed {sens:.2f}\n")
    if p["mouseAccelProfile"] in ("flat", "adaptive"):
        out.append(f"        accel-profile \"{p['mouseAccelProfile']}\"\n")
    out.append(f"        scroll-factor {float(p['mouseScrollFactor']):.2f}\n")
    out.append(flag("natural-scroll", p["mouseNaturalScroll"], "        "))
    out.append(flag("left-handed", p["mouseLeftHanded"], "        "))
    out.append("    }\n    touchpad {\n")
    out.append(flag("tap", p["touchpadTapToClick"], "        "))
    out.append(flag("natural-scroll", p["touchpadNaturalScroll"], "        "))
    out.append(flag("dwt", p["touchpadDisableWhileTyping"], "        "))
    out.append("    }\n")
    if p["focusFollowsMouse"]:
        out.append("    focus-follows-mouse max-scroll-amount=\"0%\"\n")
    out.append("}\n")

    timeout = int(p["cursorInactiveTimeout"])
    if timeout > 0:
        out.append(f"cursor {{\n    hide-after-inactive-ms {timeout * 1000}\n}}\n")
    return "".join(out)


def save(prefs):
    os.makedirs(os.path.dirname(PREFS), exist_ok=True)
    with open(PREFS, "w") as f:
        json.dump(prefs, f, indent=2)
    os.makedirs(os.path.dirname(KDL), exist_ok=True)
    tmp = KDL + ".tmp"
    with open(tmp, "w") as f:
        f.write(render(prefs))
    os.replace(tmp, KDL)


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "read"
    prefs = load()
    if cmd == "write" and len(sys.argv) > 2:
        prefs.update({k: v for k, v in json.loads(sys.argv[2]).items() if k in DEFAULTS})
        save(prefs)
    elif cmd == "render":
        save(prefs)
    print(json.dumps(prefs))


if __name__ == "__main__":
    main()
